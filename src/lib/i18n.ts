const dictionaries: Record<Language, Record<Key, Entry>> = { en, de };

// ---------------------------------------------------------------------------
// Current language: a tiny store so every screen follows the setting at once.

let current: Language = 'en';
const listeners = new Set<() => void>();

export function getLanguage() {
  return current;
}

export function setLanguage(language: Language) {
  if (language === current) return;
  current = language;
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

/** The current language; re-renders the component when it changes. */
export function useLanguage() {
  return useSyncExternalStore(subscribe, getLanguage, getLanguage);
}

export type Vars = Record<string, string | number>;

function translate(language: Language, key: Key, vars?: Vars): string {
  const entry = dictionaries[language][key] ?? en[key];
  const text = typeof entry === 'string' ? entry : Number(vars?.n) === 1 ? entry.one : entry.other;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function t(key: Key, vars?: Vars): string {
  return translate(current, key, vars);
}

/** The entry in every language, for matching stored text whichever language wrote it. */
export function everyLanguage(key: Key): string[] {
  return Object.values(dictionaries).map((dict) => {
    const entry = dict[key];
    return typeof entry === 'string' ? entry : entry.other;
  });
}

/**
 * `t` for components: subscribes to the language so the strings follow it. The function
 * changes identity with the language, so memoized JSX (React Compiler) is recomputed too.
 */
export function useT() {
  const language = useLanguage();
  return useMemo(() => (key: Key, vars?: Vars) => translate(language, key, vars), [language]);
}

/** BCP 47 tag for dates and numbers in the current language. */
export function locale() {
  return current === 'de' ? 'de-CH' : 'en-GB';
}
